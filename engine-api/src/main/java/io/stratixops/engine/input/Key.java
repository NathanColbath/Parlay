package io.stratixops.engine.input;

/**
 * Physical keys the MVP can bind. Mirrors the subset of keyboard keys the
 * sample game uses; the implementation may expose more.
 */
public enum Key {
    /** W key. */
    W,
    /** A key. */
    A,
    /** S key. */
    S,
    /** D key. */
    D,
    /** Up arrow. */
    UP,
    /** Left arrow. */
    LEFT,
    /** Down arrow. */
    DOWN,
    /** Right arrow. */
    RIGHT,
    /** Space bar. */
    SPACE,
    /** Enter / Return. */
    ENTER,
    /** Escape. */
    ESCAPE,
    /** P key. */
    P,
    /** M key. */
    M
}
